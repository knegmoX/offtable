const dicts: Record<Locale, Partial<Dict>> = { 'zh-Hans': zhHans, 'zh-Hant': zhHant, en };

export function detectLocale(): Locale {
  const langs = (navigator.languages?.length ? navigator.languages : [navigator.language || 'en']).map((l) =>
    l.toLowerCase(),
  );
  for (const l of langs) {
    if (l.startsWith('zh')) {
      return /hant|tw|hk|mo/.test(l) ? 'zh-Hant' : 'zh-Hans';
    }
    if (l.startsWith('en')) return 'en';
  }
  return 'en';
}

export const locale = signal<Locale>(detectLocale());

export type Key = keyof typeof zhHans;

export function t(key: Key, vars?: Record<string, string>): string {
  let s = dicts[locale.value][key] ?? zhHans[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, v);
  return s;
}

export function errText(code: string): string {
  const k = ('err.' + code) as Key;
  return k in zhHans ? t(k) : t('err.generic');
}
